-- 全类型覆盖：布尔、整数、定点、浮点、两种时间戳、date、time、bytea、json/jsonb、UUID、数组
CREATE TABLE t_types (
    id      int PRIMARY KEY,
    b       boolean,
    si      smallint,
    i       int,
    bi      bigint,
    nu      numeric(12,3),
    r       real,
    d       double precision,
    ts      timestamp,
    tstz    timestamptz,
    da      date,
    tm      time,
    bl      bytea,
    tx      text,
    u       uuid,
    js      json,
    jsb     jsonb,
    ta      text[],
    ia      int[]
);

